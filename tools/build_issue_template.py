#!/usr/bin/env python3
"""Write the GitHub form people use to suggest an example or statistic.

    python3 tools/build_issue_template.py

The dot point list comes from data/syllabus.js, so run this again whenever dot points change
(tests/run_tests.js fails if the form is out of date).
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / ".github" / "ISSUE_TEMPLATE" / "suggest-evidence.yml"
TYPES = ["Report", "Article", "Statistic", "Policy decision", "Speech", "Court case", "Regulation", "Research", "Trade"]


def dotpoint_options():
    options, year = [], None
    for line in (ROOT / "data" / "syllabus.js").read_text(encoding="utf-8").splitlines():
        if line.lstrip().startswith("branches:"):
            break
        y = re.search(r'\byear: (\d+)', line)
        if y:
            year = y.group(1)
        dp = re.search(r'\{ id: "([a-z0-9-]+)", short: "([^"]+)"', line)
        if dp:
            options.append(f"Year {year}: {dp.group(2)} ({dp.group(1)})")
    return options


def q(text):
    return json.dumps(text, ensure_ascii=False)


def main():
    dps = dotpoint_options()
    lines = [
        "# Generated by tools/build_issue_template.py. Edit that script, not this file.",
        "name: Suggest an example or statistic",
        "description: Send a report, article, decision or statistic for Dotpoint. Every suggestion is checked before it goes on the site.",
        'title: "Suggestion: "',
        "labels: [submission]",
        "body:",
        "  - type: markdown",
        "    attributes:",
        "      value: |",
        "        Thanks for helping. Use official sources where you can (RBA, ABS, ACCC, ATO, Treasury, Fair Work).",
        "        Every fact in your summary must appear on the page you link to. The site owner reads each suggestion",
        "        and, once approved, it is added to Dotpoint automatically.",
        "  - type: input",
        "    id: headline",
        "    attributes:",
        "      label: Headline",
        "      description: A short, plain title, for example Unemployment edges up to 4.7%",
        "    validations:",
        "      required: true",
        "  - type: dropdown",
        "    id: type",
        "    attributes:",
        "      label: Type",
        "      options: [" + ", ".join(q(t) for t in TYPES) + "]",
        "    validations:",
        "      required: true",
        "  - type: input",
        "    id: source_name",
        "    attributes:",
        "      label: Who published it?",
        "      description: For example ABS media release, 15 Oct 2026",
        "    validations:",
        "      required: true",
        "  - type: input",
        "    id: source_url",
        "    attributes:",
        "      label: Link to the source",
        "      placeholder: https://",
        "    validations:",
        "      required: true",
        "  - type: input",
        "    id: date",
        "    attributes:",
        "      label: Date it happened or was released",
        "      description: Written as YYYY-MM-DD, for example 2026-10-15",
        "    validations:",
        "      required: true",
        "  - type: input",
        "    id: key_figure",
        "    attributes:",
        "      label: Key figure",
        "      description: The number to remember, in under 40 characters, for example 4.7% unemployed",
        "    validations:",
        "      required: true",
        "  - type: textarea",
        "    id: summary",
        "    attributes:",
        "      label: What it shows, in your own words",
        "      description: Two to four sentences, under 520 characters. Include the figures.",
        "    validations:",
        "      required: true",
        "  - type: textarea",
        "    id: use_for",
        "    attributes:",
        "      label: How a student could use it in an essay",
        "    validations:",
        "      required: true",
        "  - type: dropdown",
        "    id: dotpoints",
        "    attributes:",
        "      label: Dot points it supports",
        "      description: Pick one or more.",
        "      multiple: true",
        "      options:",
    ]
    lines += [f"        - {q(o)}" for o in dps]
    lines += [
        "    validations:",
        "      required: true",
        "  - type: input",
        "    id: quote",
        "    attributes:",
        "      label: A short quote copied exactly from the source",
        "      description: One sentence or part of one, 22 words at most, word for word, without quotation marks.",
        "    validations:",
        "      required: true",
        "  - type: input",
        "    id: quote_by",
        "    attributes:",
        "      label: Who said or wrote the quote",
        "      description: For example Sean Crick, ABS head of labour statistics, 1 Oct 2026",
        "    validations:",
        "      required: true",
        "  - type: checkboxes",
        "    id: checks",
        "    attributes:",
        "      label: Before you send",
        "      options:",
        "        - label: Every fact in my summary appears on the page I linked to.",
        "          required: true",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} with {len(dps)} dot points")


if __name__ == "__main__":
    main()
