#!/usr/bin/env python3
"""Draw the Dotpoint mark: a yellow dot, with a loose ink ring drawn slightly off it and one note line on it.

    python3 tools/build_icons.py

The ring is a quick hand-drawn loop that overshoots where it started, sitting up and to the left of the
dot like a misprint. It is the same drawing as the logo in index.html. Writes icons/favicon.svg (its ink
turns light on dark tabs), icons/favicon-32.png and icons/apple-touch-icon.png. No libraries needed.
"""
import math
import struct
import zlib
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "icons"
YELLOW, INK, PAPER = (0xEE, 0xDD, 0x3A), (0x18, 0x21, 0x1D), (0xF3, 0xF5, 0xF1)

# In a 64 x 64 box. Keep these in step with the logo <svg> in index.html.
DOT = (37, 37)
DOT_R = 21
STROKE = 6.5
# Each path: a start point, then cubic Bézier segments (control, control, end).
RING = [(40, 8), ((24, 2), (6, 13), (6.5, 30)), ((7, 46), (20, 52.5), (30, 51.5)),
        ((44, 50.5), (51.5, 40), (50.5, 27)), ((49.5, 14), (38, 5.5), (24, 8.5))]
# The note line sits wholly on the yellow, so it stays dark ink in both light and dark tabs.
LINE = [(23, 26), ((27, 24.5), (33, 27), (39.5, 25))]


def path_d(path):
    d = "M{} {}".format(*path[0])
    for c1, c2, end in path[1:]:
        d += " C{} {} {} {} {} {}".format(*c1, *c2, *end)
    return d


def svg():
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <!-- Generated by tools/build_icons.py -->
  <style>
    .ink {{ stroke: #18211d; }}
    @media (prefers-color-scheme: dark) {{ .ink {{ stroke: #e6ece7; }} }}
  </style>
  <circle cx="{DOT[0]}" cy="{DOT[1]}" r="{DOT_R}" fill="#eedd3a"/>
  <g fill="none" stroke-width="{STROKE}" stroke-linecap="round">
    <path class="ink" d="{path_d(RING)}"/>
    <path d="{path_d(LINE)}" stroke="#18211d"/>
  </g>
</svg>
"""


def flatten(path, steps=16):
    pts = [path[0]]
    for c1, c2, end in path[1:]:
        p0 = pts[-1]
        for i in range(1, steps + 1):
            t = i / steps
            u = 1 - t
            pts.append(tuple(u ** 3 * p0[k] + 3 * u * u * t * c1[k] + 3 * u * t * t * c2[k] + t ** 3 * end[k] for k in range(2)))
    return list(zip(pts, pts[1:]))


def seg_dist(px, py, a, b):
    (x1, y1), (x2, y2) = a, b
    dx, dy = x2 - x1, y2 - y1
    t = max(0, min(1, ((px - x1) * dx + (py - y1) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (x1 + t * dx), py - (y1 + t * dy))


SEGS = flatten(RING) + flatten(LINE)
HALF = STROKE / 2
BOXES = [(min(a[0], b[0]) - HALF, max(a[0], b[0]) + HALF, min(a[1], b[1]) - HALF, max(a[1], b[1]) + HALF) for a, b in SEGS]


def on_ink(x, y):
    for (a, b), (x0, x1, y0, y1) in zip(SEGS, BOXES):
        if x0 <= x <= x1 and y0 <= y <= y1 and seg_dist(x, y, a, b) <= HALF:
            return True
    return False


def png(size, path, pad=0.0, background=None):
    scale = 64 / (size * (1 - 2 * pad))
    off = size * pad
    ss = 4
    rows = []
    for py in range(size):
        row = bytearray([0])
        for px in range(size):
            ink = yellow = 0
            for sy in range(ss):
                for sx in range(ss):
                    x = (px + (sx + 0.5) / ss - off) * scale
                    y = (py + (sy + 0.5) / ss - off) * scale
                    if on_ink(x, y):
                        ink += 1                          # the ink sits on top of the dot
                    elif math.hypot(x - DOT[0], y - DOT[1]) <= DOT_R:
                        yellow += 1
            n = ss * ss
            ia, ya = ink / n, yellow / n
            a = ia + ya
            col = [(INK[i] * ia + YELLOW[i] * ya) / a for i in range(3)] if a else [0, 0, 0]
            if background:
                row += bytes([round(col[i] * a + background[i] * (1 - a)) for i in range(3)] + [255])
            else:
                row += bytes([round(c) for c in col] + [round(255 * a)])
        rows.append(bytes(row))

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    path.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
                     + chunk(b"IDAT", zlib.compress(b"".join(rows), 9)) + chunk(b"IEND", b""))


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    (OUT / "favicon.svg").write_text(svg(), encoding="utf-8")
    png(32, OUT / "favicon-32.png")
    png(180, OUT / "apple-touch-icon.png", pad=0.14, background=PAPER)
    print("Wrote icons/favicon.svg, icons/favicon-32.png, icons/apple-touch-icon.png")
    print("Logo paths for index.html:")
    print("  ring:", path_d(RING))
    print("  line:", path_d(LINE))
