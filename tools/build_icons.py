#!/usr/bin/env python3
"""Draw the Dotpoint mark: a short rising chart line that ends in the yellow dot.

    python3 tools/build_icons.py

It is the same shape the site's charts use (every line ends in a yellow dot), and the same
drawing as the logo in index.html. Writes icons/favicon.svg (its ink turns light on dark tabs),
icons/favicon-32.png and icons/apple-touch-icon.png. No libraries needed.
"""
import math
import struct
import zlib
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "icons"
YELLOW, INK, PAPER = (0xEE, 0xDD, 0x3A), (0x18, 0x21, 0x1D), (0xF3, 0xF5, 0xF1)

# In a 64 x 64 box. Keep these in step with the logo <svg> in index.html.
LINE = [(7, 51), (21, 37), (31, 43), (45, 21)]
LINE_WIDTH = 6.5
DOT = (45, 21)
DOT_R = 12        # radius of the yellow fill, measured to the middle of the ring
RING = 5          # ring thickness


def svg():
    pts = " ".join(f"{x},{y}" for x, y in LINE)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <!-- Generated by tools/build_icons.py -->
  <style>
    .ink {{ stroke: #18211d; }}
    @media (prefers-color-scheme: dark) {{ .ink {{ stroke: #e6ece7; }} }}
  </style>
  <polyline class="ink" points="{pts}" fill="none" stroke-width="{LINE_WIDTH}" stroke-linecap="round" stroke-linejoin="round"/>
  <circle class="ink" cx="{DOT[0]}" cy="{DOT[1]}" r="{DOT_R}" fill="#eedd3a" stroke-width="{RING}"/>
</svg>
"""


def seg_dist(px, py, a, b):
    (x1, y1), (x2, y2) = a, b
    dx, dy = x2 - x1, y2 - y1
    t = max(0, min(1, ((px - x1) * dx + (py - y1) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (x1 + t * dx), py - (y1 + t * dy))


def png(size, path, pad=0.0, background=None):
    scale = 64 / (size * (1 - 2 * pad))
    off = size * pad
    ss = 4
    rows = []
    for py in range(size):
        row = bytearray([0])
        for px in range(size):
            ink = yellow = 0
            for sy in range(ss):
                for sx in range(ss):
                    x = (px + (sx + 0.5) / ss - off) * scale
                    y = (py + (sy + 0.5) / ss - off) * scale
                    d = math.hypot(x - DOT[0], y - DOT[1])
                    if d <= DOT_R - RING / 2:
                        yellow += 1                       # the dot sits on top of the line
                    elif d <= DOT_R + RING / 2:
                        ink += 1
                    elif min(seg_dist(x, y, LINE[i], LINE[i + 1]) for i in range(len(LINE) - 1)) <= LINE_WIDTH / 2:
                        ink += 1
            n = ss * ss
            ia, ya = ink / n, yellow / n
            a = ia + ya
            col = [(INK[i] * ia + YELLOW[i] * ya) / a for i in range(3)] if a else [0, 0, 0]
            if background:
                row += bytes([round(col[i] * a + background[i] * (1 - a)) for i in range(3)] + [255])
            else:
                row += bytes([round(c) for c in col] + [round(255 * a)])
        rows.append(bytes(row))

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    path.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
                     + chunk(b"IDAT", zlib.compress(b"".join(rows), 9)) + chunk(b"IEND", b""))


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    (OUT / "favicon.svg").write_text(svg(), encoding="utf-8")
    png(32, OUT / "favicon-32.png")
    png(180, OUT / "apple-touch-icon.png", pad=0.16, background=PAPER)
    print("Wrote icons/favicon.svg, icons/favicon-32.png, icons/apple-touch-icon.png")
